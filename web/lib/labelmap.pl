#!/usr/bin/env perl
# Reads the book's LaTeX sources and emits either:
#   (default)    the label -> {page, anchor, title} Lua table that asterion.lua uses to
#                turn \Cref{...} into real links (to another page, or within the EPUB)
#   --chapters   a TSV of the chapters in document order: file <TAB> slug <TAB> title
#
# Chapter order comes from the \subfile lines of main.tex; chapter titles and labels, and
# the labels of sections, from the chapter files themselves.
#
#   perl web/lib/labelmap.pl <repo-root> [--chapters]
use strict;
use warnings;
binmode(STDOUT, ":encoding(UTF-8)");

my ($src, $mode) = @ARGV;
die "usage: labelmap.pl <repo-root> [--chapters]\n" unless defined $src;

my (%map, @chapters);

my $main = slurp("$src/main.tex");
$main =~ s/(?<!\\)%[^\n]*//g;                       # comments
while ($main =~ /\\subfile\{chapters\/([^}]+)\}/g) {
    my $file = $1;
    my $tex  = slurp("$src/chapters/$file.tex");
    my ($title, $label) = ('', '');
    if ($tex =~ /\\chapter\*?\{((?:[^{}]|\{[^{}]*\})*)\}\s*(?:\\label\{([^}]+)\})?/) {
        ($title, $label) = (clean($1), $2 // '');
    } elsif ($tex =~ /\\section\*?\{((?:[^{}]|\{[^{}]*\})*)\}/) {
        $title = clean($1);                             # appendix parts start with a section
    }
    (my $slug = $file) =~ s{/}{-}g;       # dodatky/uvod -> dodatky-uvod (no clash with uvod)
    $slug =~ tr/_/-/;
    push @chapters, { file => $file, slug => $slug, title => $title };
    $map{$label} = { page => $slug, anchor => '', title => $title } if $label ne '';

    # sections, and anything else labelled right after a heading
    while ($tex =~ /\\(?:sub){0,2}section\*?\{((?:[^{}]|\{[^{}]*\})*)\}\s*(?:%[^\n]*)?\s*\n?\s*\\label\{([^}]+)\}/gs) {
        $map{$2} = { page => $slug, anchor => $2, title => clean($1) };
    }
}
die "labelmap: found no chapters in $src/main.tex\n" unless @chapters;

if (defined $mode && $mode eq '--chapters') {
    print join("\t", $_->{file}, $_->{slug}, $_->{title}), "\n" for @chapters;
    exit 0;
}

print "-- generated by web/lib/labelmap.pl; do not edit\n";
print "return {\n";
for my $l (sort keys %map) {
    printf qq(  ["%s"] = { page = "%s", anchor = "%s", title = "%s" },\n),
        esc($l), $map{$l}{page}, esc($map{$l}{anchor}), esc($map{$l}{title});
}
print "}\n";

sub slurp {
    my ($f) = @_;
    open my $fh, '<:encoding(UTF-8)', $f or die "labelmap: $f: $!\n";
    local $/; <$fh>;
}

sub esc { my ($s) = @_; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return $s }

# a heading's text without TeX markup
sub clean {
    my ($t) = @_;
    $t =~ s/\\(?:emph|textit|textbf|texttt|asp|dov|trk|akc|per)\{([^{}]*)\}/$1/g;
    $t =~ s/\\([&%\$#_{}])/$1/g;
    $t =~ s/\\[a-zA-Z]+\*?\s*//g;
    $t =~ s/[{}]//g;
    $t =~ s/``|''/"/g;
    $t =~ s/^\s+|\s+$//g;
    return $t;
}
